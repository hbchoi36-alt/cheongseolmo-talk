// 구글폼 한국어 내려받기 형식의 타임스탬프 (예: 2026. 10. 20 오전 9:05:00)
function timestamp(index) {
  const day = 20 + Math.floor(index / 6);
  const minutes = 9 * 60 + index * 23;
  const hour24 = Math.floor(minutes / 60);
  const ampm = hour24 < 12 ? "오전" : "오후";
  const hour12 = hour24 % 12 === 0 ? 12 : hour24 % 12;
  const mm = String(minutes % 60).padStart(2, "0");
  const ss = String((index * 17) % 60).padStart(2, "0");
  return `2026. 10. ${day} ${ampm} ${hour12}:${mm}:${ss}`;
}

const table = [
  HEADERS,
  ...ROWS.map(([areas, ...answers], i) => [timestamp(i), areas.join(", "), ...answers]),
];

// 쉼표·따옴표·줄바꿈이 있는 칸만 따옴표로 감싼다 (구글폼·엑셀과 같은 방식)
function toCsv(rows) {
  const cell = (value) => (/[",\r\n]/.test(value) ? `"${value.replaceAll('"', '""')}"` : value);
  return rows.map((row) => row.map(cell).join(",")).join("\r\n") + "\r\n";
}

const csv = toCsv(table);

// 1) 구글폼에서 바로 내려받은 CSV (UTF-8)
writeFileSync(new URL("opinions-utf8.csv", OUT_DIR), csv, "utf8");

// 2) 엑셀에서 다시 저장해 한글 인코딩이 바뀐 CSV (CP949)
writeFileSync(new URL("opinions-cp949.csv", OUT_DIR), iconv.encode(csv, "cp949"));

// 3) 엑셀 파일 — 구글 스프레드시트 기본 시트 이름 사용
await writeExcelFile(table, { sheet: "설문지 응답 시트1" }).toFile(
  new URL("opinions.xlsx", OUT_DIR).pathname.replace(/^\/([A-Za-z]:)/, "$1"),
);

